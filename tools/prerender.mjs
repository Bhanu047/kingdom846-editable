/**
 * Write one static HTML file per public route into dist/.
 *
 * The portal is a single-page app: the document the server sends is an empty
 * shell, and every word a visitor reads is painted by JavaScript afterwards.
 * Search engines do run JavaScript, but they run it later, on a separate pass,
 * and rank what they found on the first one. A shell whose <title> and
 * description are the same on every route tells them the site is one page.
 *
 * So each route gets its own copy of the shell with its own <title>,
 * description, canonical and Open Graph tags baked in. The app still boots and
 * takes over exactly as before -- only the head differs, and it differs to say
 * what that page actually is. Private routes get noindex instead.
 *
 * Run after `vite build`; the npm build script chains it.
 */
import fs from 'node:fs'
import path from 'node:path'
import { ROUTES, SITE_ORIGIN } from '../src/data/routes.js'

const DIST = path.join(process.cwd(), 'dist')
const shell = fs.readFileSync(path.join(DIST, 'index.html'), 'utf8')

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;')
                    .replace(/>/g, '&gt;').replace(/"/g, '&quot;')

// Replace the content of a tag that is already in the shell, or append it to
// <head> if the shell does not carry one.
function setTag(html, pattern, replacement) {
  return pattern.test(html) ? html.replace(pattern, replacement)
                            : html.replace('</head>', `  ${replacement}\n</head>`)
}

let written = 0
for (const r of ROUTES) {
  let html = shell
  const url = SITE_ORIGIN + r.path
  const desc = r.description || ''

  html = setTag(html, /<title>[\s\S]*?<\/title>/, `<title>${esc(r.title)}</title>`)
  html = setTag(html, /<link rel="canonical"[^>]*>/, `<link rel="canonical" href="${esc(url)}" />`)
  html = setTag(html, /<meta property="og:url"[^>]*>/, `<meta property="og:url" content="${esc(url)}" />`)
  html = setTag(html, /<meta property="og:title"[^>]*>/, `<meta property="og:title" content="${esc(r.title)}" />`)
  html = setTag(html, /<meta name="twitter:title"[^>]*>/, `<meta name="twitter:title" content="${esc(r.title)}" />`)

  if (desc) {
    html = setTag(html, /<meta name="description"[^>]*>/, `<meta name="description" content="${esc(desc)}" />`)
    html = setTag(html, /<meta property="og:description"[^>]*>/, `<meta property="og:description" content="${esc(desc)}" />`)
    html = setTag(html, /<meta name="twitter:description"[^>]*>/, `<meta name="twitter:description" content="${esc(desc)}" />`)
  }

  if (r.index === false) {
    html = setTag(html, /<meta name="robots"[^>]*>/, '<meta name="robots" content="noindex, nofollow" />')
  }

  // "/" is index.html itself; everything else becomes <route>.html, which the
  // server prefers over the SPA fallback when it exists.
  const out = r.path === '/' ? 'index.html' : `${r.path.replace(/^\//, '')}.html`
  fs.writeFileSync(path.join(DIST, out), html)
  written++
}

// sitemap.xml, generated rather than hand-kept, so it cannot drift from the
// routes the app actually serves.
const urls = ROUTES.filter((r) => r.index).map((r) =>
  `  <url>\n    <loc>${SITE_ORIGIN}${r.path}</loc>\n` +
  `    <changefreq>${r.changefreq}</changefreq>\n    <priority>${r.priority}</priority>\n  </url>`
).join('\n')
fs.writeFileSync(path.join(DIST, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by tools/prerender.mjs. Do not edit by hand. -->\n` +
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`)

console.log(`prerendered ${written} routes; sitemap lists ${ROUTES.filter((r) => r.index).length}`)
